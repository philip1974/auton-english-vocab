#!/usr/bin/env python3
"""Build conservative ambiguous-inflection surfaces from bundled ECDICT data."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "src" / "ambiguous-inflections.generated.mjs"
REVIEWED_INPUT = ROOT / "src" / "ambiguous-inflections.reviewed.mjs"
INFLECTION_TEXT = re.compile(
    r"[^\s，,；;（）()]{1,30}的(?:过去式(?:和过去分词)?|过去分词|现在分词|"
    r"第三人称单数(?:形式)?|名词复数(?:形式)?|复数(?:形式)?|比较级|最高级)",
    re.IGNORECASE,
)
PAREN_INFLECTION_TEXT = re.compile(
    r"[（(][^（）()]*(?:过去式|过去分词|现在分词|复数|第三人称|比较级|最高级)[^（）()]*[）)]",
    re.IGNORECASE,
)
POS_LINE = re.compile(r"(?:^|\n)\s*(n|v|vt|vi|a|adj|adv)\.\s*", re.IGNORECASE)
PARADIGM_KEYS = ("s", "d", "p", "i", "3")


def load_chunk(path: Path) -> dict[str, dict[str, object]]:
    text = path.read_text(encoding="utf-8")
    prefix = "export default "
    if not text.startswith(prefix) or not text.rstrip().endswith(";"):
        raise ValueError(f"unexpected dictionary module format: {path}")
    return json.loads(text[len(prefix):].rstrip()[:-1])


def exchange_parts(value: object) -> dict[str, str]:
    parts: dict[str, str] = {}
    for item in str(value or "").split("/"):
        if ":" not in item:
            continue
        key, content = item.split(":", 1)
        parts[key] = content
    return parts


def semantic_translation(value: object) -> str:
    text = PAREN_INFLECTION_TEXT.sub("", str(value or ""))
    text = INFLECTION_TEXT.sub("", text)
    text = POS_LINE.sub("\n", text)
    return re.sub(r"[\s,，;；.。()（）&/\-]", "", text)


def independent_lexical_entry(entry: dict[str, object]) -> bool:
    text = str(entry.get("t") or "")
    positions = {match.group(1).lower() for match in POS_LINE.finditer(text)}
    return bool(positions & {"n", "v", "vt", "vi"}) and bool(semantic_translation(text))


def build(frequency_limit: int) -> list[dict[str, object]]:
    frequency = json.loads((ROOT / "data" / "en-wordfreq-30k.json").read_text(encoding="utf-8"))
    ranks = {word: index for index, word in enumerate(frequency[:frequency_limit])}
    entries: dict[str, dict[str, object]] = {}
    for path in sorted((ROOT / "dict").glob("[a-z].mjs")):
        entries.update(load_chunk(path))
    candidates: dict[str, set[str]] = {}
    for lemma, entry in entries.items():
        parts = exchange_parts(entry.get("x"))
        for kind in PARADIGM_KEYS:
            surface = parts.get(kind, "").lower()
            target = entries.get(surface)
            if not surface or surface == lemma or surface not in ranks or not target or not independent_lexical_entry(target):
                continue
            target_lemma = exchange_parts(target.get("x")).get("0")
            competing_lemma = bool(target_lemma and target_lemma != lemma)
            irregular_past = kind in {"d", "p"} and not surface.endswith("ed")
            if competing_lemma or irregular_past:
                reasons = candidates.setdefault(surface, set())
                reasons.add(f"{lemma}:{kind}")
                if competing_lemma:
                    reasons.add(f"surface-lemma:{target_lemma}")
                if irregular_past:
                    reasons.add("irregular-past-or-participle")
    return [
        {"surface": surface, "rank": ranks[surface] + 1, "reasons": sorted(candidates[surface])}
        for surface in sorted(candidates, key=lambda word: (ranks[word], word))
    ]


def render(candidates: list[dict[str, object]], frequency_limit: int) -> str:
    values = ",\n".join(f"  Object.freeze({json.dumps(item, ensure_ascii=False, separators=(',', ':'))})" for item in candidates)
    return (
        "// Generated by scripts/build-ambiguous-inflections.py; do not edit manually.\n"
        "export const AMBIGUOUS_INFLECTION_METADATA = Object.freeze({\n"
        "  source: 'dict/*.mjs + data/en-wordfreq-30k.json',\n"
        f"  frequencyLimit: {frequency_limit},\n"
        f"  count: {len(candidates)},\n"
        "});\n\n"
        "export const AMBIGUOUS_INFLECTION_CANDIDATES = Object.freeze([\n"
        f"{values}\n"
        "]);\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--frequency-limit", type=int, default=5000)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    candidates = build(args.frequency_limit)
    content = render(candidates, args.frequency_limit)
    output = args.output if args.output.is_absolute() else ROOT / args.output
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != content:
            raise SystemExit(f"generated ambiguity table is stale: {output}")
        reviewed = re.findall(r"surface:\s*'([^']+)'", REVIEWED_INPUT.read_text(encoding="utf-8"))
        candidate_surfaces = {str(item["surface"]) for item in candidates}
        missing = [word for word in reviewed if word not in candidate_surfaces]
        if missing:
            raise SystemExit(f"reviewed ambiguity surfaces are no longer candidates: {', '.join(missing)}")
        return
    output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
